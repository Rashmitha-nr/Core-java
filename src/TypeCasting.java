public class TypeCasting {
    public static void main(String[] args) {
        int a=14; // Implicit
        long l=a;
        System.out.println(l);
         long b=1234; //Explicit
         int i=(int)b;
         System.out.println(i);
         int r=104;// Implicit
         float f=r;
        System.out.println(f);
        float c=14.56f; // explicit
        int i1=(int)c;
        System.out.println(i1);

    }
}
