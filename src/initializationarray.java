public class initializationarray {
    public static void main(String[] args) {
        int a[]=new int[4];        //syntax for initialization of array
        a[0]=1;
        a[1]=7;
        a[2]=9;
        a[3]=6;
        for(int i=0;i<a.length;i++){
            System.out.println(a[i]);
        }
    }
}
